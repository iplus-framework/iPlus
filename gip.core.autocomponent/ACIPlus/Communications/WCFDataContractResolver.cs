﻿using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Runtime.Serialization;
using System.Data;
using gip.core.datamodel;
using System.ComponentModel;
using System.Xml;

namespace gip.core.autocomponent
{
    public class WCFDataContractResolver : DataContractResolver
    {
        public override Type ResolveName(string typeName, string typeNamespace, Type declaredType, DataContractResolver knownTypeResolver)
        {
            Type resolvedType = null;
            if (typeName == "XmlACEventArgs")
                return TypeACEventArgs;
            else if (typeName == "XmlACMethodEventArgs")
                return TypeACMethodEventArgs;
            else if (typeName == "XmlStringArray")
                return TypeStringArray;
            else if (typeName == "XmlStringArrayValueEvent")
                return TypeStringArrayValueEvent;
            else
                resolvedType = knownTypeResolver.ResolveName(typeName, typeNamespace, declaredType, null);
            if (resolvedType == null)
                resolvedType = ResolveClosedGenericFallback(typeName, typeNamespace);
            return resolvedType;
        }

        #region Closed generic fallback

        // Cache for types resolved from the wire, keyed by "typeName|typeNamespace"
        static Dictionary<string, Type> _ResolvedGenericCache = new Dictionary<string, Type>();
        static System.Collections.Concurrent.ConcurrentDictionary<string, Type[]> _TypesByNamespaceCache = new System.Collections.Concurrent.ConcurrentDictionary<string, Type[]>();

        /// <summary>
        /// Fallback resolver for closed generic types whose DataContract name is not resolvable
        /// through the known-type resolver (typical on proxy clients that have not registered
        /// e.g. ACPropertyValueEvent<ACRef<Facility>> because the server-side component assembly
        /// was never scanned client-side).
        /// DataContract names of closed generics follow the pattern
        ///   <GenericDefName>Of<ParamDcName>[hash]
        /// where the optional hash suffix is generated by DataContractSerializer for shared
        /// generic contracts. We match the generic definition by prefix and recursively resolve
        /// the generic arguments.
        /// </summary>
        Type ResolveClosedGenericFallback(string typeName, string typeNamespace)
        {
            if (String.IsNullOrEmpty(typeName) || String.IsNullOrEmpty(typeNamespace))
                return null;
            string cacheKey = typeName + "|" + typeNamespace;
            lock (_ResolvedGenericCache)
            {
                Type cached;
                if (_ResolvedGenericCache.TryGetValue(cacheKey, out cached))
                    return cached;
            }
            try
            {
                // "http://schemas.datacontract.org/2004/07/gip.core.autocomponent" -> "gip.core.autocomponent"
                const string dcPrefix = "http://schemas.datacontract.org/2004/07/";
                string clrNamespace = typeNamespace.StartsWith(dcPrefix, StringComparison.Ordinal)
                    ? typeNamespace.Substring(dcPrefix.Length)
                    : null;
                if (clrNamespace == null)
                    return null;

                Type[] candidates = GetTypesInNamespace(clrNamespace);
                if (candidates == null || candidates.Length == 0)
                    return null;

                // Find a generic type definition whose (backtick-stripped) name is a prefix of
                // the wire name followed by "Of". Prefer the longest match.
                Type genericDef = null;
                string paramPart = null;
                foreach (Type t in candidates)
                {
                    if (!t.IsGenericTypeDefinition)
                        continue;
                    string defName = t.Name;
                    int backtick = defName.IndexOf('`');
                    if (backtick > 0)
                        defName = defName.Substring(0, backtick);
                    if (typeName.Length <= defName.Length + 2)
                        continue;
                    if (!typeName.StartsWith(defName, StringComparison.Ordinal))
                        continue;
                    if (typeName[defName.Length] != 'O' || typeName[defName.Length + 1] != 'f')
                        continue;
                    if (genericDef == null || defName.Length > genericDef.Name.Length)
                    {
                        genericDef = t;
                        paramPart = typeName.Substring(defName.Length + 2);
                    }
                }
                if (genericDef == null)
                    return null;

                // Resolve generic arguments recursively
                string[] paramNames = SplitGenericArgs(paramPart, genericDef.GetGenericArguments().Length);
                if (paramNames == null)
                    return null;
                Type[] args = new Type[paramNames.Length];
                for (int i = 0; i < paramNames.Length; i++)
                {
                    args[i] = ResolveTypeByDcName(paramNames[i]);
                    if (args[i] == null)
                        return null;
                }
                Type closed = genericDef.MakeGenericType(args);
                lock (_ResolvedGenericCache)
                {
                    _ResolvedGenericCache[cacheKey] = closed;
                }
                if (Database.Root != null && Database.Root.Messages != null)
                    Database.Root.Messages.LogDebug("WCFDataContractResolver", "ResolveClosedGenericFallback", "Resolved " + typeName + " -> " + closed.AssemblyQualifiedName);
                return closed;
            }
            catch (Exception e)
            {
                if (Database.Root != null && Database.Root.Messages != null)
                    Database.Root.Messages.LogDebug("WCFDataContractResolver", "ResolveClosedGenericFallback", "Failed for " + typeName + ": " + e.Message);
                return null;
            }
        }

        /// <summary>
        /// Splits a DataContract generic argument list into the individual argument DC names.
        /// Nested generics use parentheses: e.g. "ListOfInt32" or "ACRefOfFacility". For multi-
        /// argument generics the DC name concatenates args separated by nothing but we can only
        /// disambiguate by matching known type names, so we try greedy longest-prefix matching
        /// against loaded types.
        /// </summary>
        string[] SplitGenericArgs(string paramPart, int argCount)
        {
            if (argCount == 1)
                return new string[] { paramPart };
            // Multi-arg: greedy split by matching known simple type names
            string[] result = new string[argCount];
            if (!SplitRecursive(paramPart, argCount, result, 0))
                return null;
            return result;
        }

        bool SplitRecursive(string remaining, int argsLeft, string[] result, int index)
        {
            if (argsLeft == 0)
                return remaining.Length == 0;
            // Try every possible prefix that matches a loaded type's DC name
            foreach (string candidate in GetAllSimpleTypeNames())
            {
                if (!remaining.StartsWith(candidate, StringComparison.Ordinal))
                    continue;
                string rest = remaining.Substring(candidate.Length);
                if (argsLeft == 1)
                {
                    // Last argument: keep the remainder (may contain a hash suffix) attached
                    result[index] = remaining;
                    return true;
                }
                result[index] = candidate;
                if (SplitRecursive(rest, argsLeft - 1, result, index + 1))
                    return true;
            }
            return false;
        }

        static HashSet<string> _SimpleTypeNames = null;
        IEnumerable<string> GetAllSimpleTypeNames()
        {
            if (_SimpleTypeNames == null)
            {
                HashSet<string> names = new HashSet<string>(StringComparer.Ordinal);
                foreach (var asm in AppDomain.CurrentDomain.GetAssemblies())
                {
                    Type[] types;
                    try { types = asm.GetTypes(); }
                    catch { continue; }
                    foreach (Type t in types)
                    {
                        if (t.IsGenericTypeDefinition || t.IsGenericType)
                            continue;
                        names.Add(t.Name);
                    }
                }
                _SimpleTypeNames = names;
            }
            return _SimpleTypeNames;
        }

        /// <summary>
        /// Resolves a single DC type name like "ACRefOfFacility", "Facility",
        /// "ArrayOfACMaintWarning" (arrays) by searching loaded types. Hash suffixes appended
        /// by DataContractSerializer (variable length) are tolerated via longest-prefix matching.
        /// </summary>
        Type ResolveTypeByDcName(string dcName)
        {
            if (String.IsNullOrEmpty(dcName))
                return null;
            // Arrays: "ArrayOf" + element DC name (recursively, handles jagged arrays)
            if (dcName.Length > 7 && dcName.StartsWith("ArrayOf", StringComparison.Ordinal))
            {
                Type elementType = ResolveTypeByDcName(dcName.Substring(7));
                if (elementType != null)
                    return elementType.MakeArrayType();
            }
            // Try to interpret as closed generic: <Def>Of<Param>[hash]
            foreach (var asm in AppDomain.CurrentDomain.GetAssemblies())
            {
                Type[] types;
                try { types = asm.GetTypes(); }
                catch { continue; }
                foreach (Type t in types)
                {
                    if (!t.IsGenericTypeDefinition)
                        continue;
                    string defName = t.Name;
                    int backtick = defName.IndexOf('`');
                    if (backtick > 0)
                        defName = defName.Substring(0, backtick);
                    if (dcName.Length <= defName.Length + 2)
                        continue;
                    if (!dcName.StartsWith(defName, StringComparison.Ordinal))
                        continue;
                    if (dcName[defName.Length] != 'O' || dcName[defName.Length + 1] != 'f')
                        continue;
                    string inner = dcName.Substring(defName.Length + 2);
                    Type innerType = ResolveTypeByDcName(inner);
                    if (innerType == null)
                        continue;
                    try { return t.MakeGenericType(innerType); }
                    catch { continue; }
                }
            }
            // Otherwise: simple (non-generic) type, tolerating a trailing hash suffix
            return FindSimpleTypeByDcName(dcName);
        }

        /// <summary>
        /// Finds a non-generic type by DataContract name. First tries an exact name match;
        /// if the wire name carries a serializer hash suffix, falls back to the longest loaded
        /// type name that is a prefix of the wire name.
        /// </summary>
        Type FindSimpleTypeByDcName(string dcName)
        {
            if (String.IsNullOrEmpty(dcName))
                return null;
            Type exact = FindSimpleType(dcName);
            if (exact != null)
                return exact;
            Type best = null;
            foreach (var asm in AppDomain.CurrentDomain.GetAssemblies())
            {
                Type[] types;
                try { types = asm.GetTypes(); }
                catch { continue; }
                foreach (Type t in types)
                {
                    if (t.IsGenericType)
                        continue;
                    if (dcName.StartsWith(t.Name, StringComparison.Ordinal) && t.Name.Length > 2)
                    {
                        if (best == null || t.Name.Length > best.Name.Length)
                            best = t;
                    }
                }
            }
            return best;
        }

        Type FindSimpleType(string name)
        {
            if (String.IsNullOrEmpty(name))
                return null;
            foreach (var asm in AppDomain.CurrentDomain.GetAssemblies())
            {
                Type[] types;
                try { types = asm.GetTypes(); }
                catch { continue; }
                foreach (Type t in types)
                {
                    if (t.IsGenericType)
                        continue;
                    if (String.Equals(t.Name, name, StringComparison.Ordinal))
                        return t;
                }
            }
            return null;
        }

        Type[] GetTypesInNamespace(string clrNamespace)
        {
            return _TypesByNamespaceCache.GetOrAdd(clrNamespace, ns =>
            {
                List<Type> list = new List<Type>();
                foreach (var asm in AppDomain.CurrentDomain.GetAssemblies())
                {
                    Type[] types;
                    try { types = asm.GetTypes(); }
                    catch { continue; }
                    foreach (Type t in types)
                    {
                        if (t.Namespace == ns)
                            list.Add(t);
                    }
                }
                return list.ToArray();
            });
        }

        #endregion

        static Type _TypeACEventArgs = null;
        static Type TypeACEventArgs
        {
            get
            {
                if (_TypeACEventArgs == null)
                    _TypeACEventArgs = typeof(ACEventArgs);
                return _TypeACEventArgs;
            }
        }

        static Type _TypeACMethodEventArgs = null;
        static Type TypeACMethodEventArgs
        {
            get
            {
                if (_TypeACMethodEventArgs == null)
                    _TypeACMethodEventArgs = typeof(ACMethodEventArgs);
                return _TypeACMethodEventArgs;
            }
        }

        static Type _TypeStringArray = null;
        static Type TypeStringArray
        {
            get
            {
                if (_TypeStringArray == null)
                    _TypeStringArray = typeof(string[]);
                return _TypeStringArray;
            }
        }

        static Type _TypeStringArrayValueEvent = null;
        static Type TypeStringArrayValueEvent
        {
            get
            {
                if (_TypeStringArrayValueEvent == null)
                    _TypeStringArrayValueEvent = typeof(ACPropertyValueEvent<string[]>);
                return _TypeStringArrayValueEvent;
            }
        }

        public override bool TryResolveType(Type type, Type declaredType, DataContractResolver knownTypeResolver, out System.Xml.XmlDictionaryString typeName, out System.Xml.XmlDictionaryString typeNamespace)
        {
            bool result = false;
            if (type == TypeACEventArgs)
            {
                XmlDictionary dictionary = new XmlDictionary();
                typeName = dictionary.Add("XmlACEventArgs");
                typeNamespace = dictionary.Add("http://schemas.datacontract.org/2004/07/gip.core.datamodel");
                return true;
            }
            else if (type == TypeACMethodEventArgs)
            {
                XmlDictionary dictionary = new XmlDictionary();
                typeName = dictionary.Add("XmlACMethodEventArgs");
                typeNamespace = dictionary.Add("http://schemas.datacontract.org/2004/07/gip.core.datamodel");
                return true;
            }
            else if (type == TypeStringArray)
            {
                XmlDictionary dictionary = new XmlDictionary();
                typeName = dictionary.Add("XmlStringArray");
                typeNamespace = dictionary.Add("http://schemas.datacontract.org/2004/07/gip.core.datamodel");
                return true;
            }
            else if (type == TypeStringArrayValueEvent)
            {
                XmlDictionary dictionary = new XmlDictionary();
                typeName = dictionary.Add("XmlStringArrayValueEvent");
                typeNamespace = dictionary.Add("http://schemas.datacontract.org/2004/07/gip.core.autocomponent");
                return true;
            }

            else
            {
                result = knownTypeResolver.TryResolveType(type, declaredType, null, out typeName, out typeNamespace);
                if (!result)
                {
                    if (System.Diagnostics.Debugger.IsAttached)
                        System.Diagnostics.Debugger.Break();
                    else
                        Database.Root.Messages.LogError("WCFDataContractResolver", "TryResolveType(10)", String.Format("Cant resolve type {0}, declaredType{1}", type.AssemblyQualifiedName, declaredType.AssemblyQualifiedName));
                }
            }
            return result;
        }
    }
}
